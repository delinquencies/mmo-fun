#!/usr/bin/env bash
# Local PostgreSQL for development, kept in .dev/ (gitignored), plus generated
# secrets in .dev/env. Production must supply its own configuration.
#   tools/db/dev_db.sh init     create cluster, roles, database, secrets; run migrations
#   tools/db/dev_db.sh start | stop | status | psql | reset
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
DEV="$ROOT/.dev"
PGDATA="$DEV/pg"
PGBIN="${PGBIN:-$(ls -d /usr/lib/postgresql/*/bin 2>/dev/null | sort -V | tail -1)}"
PGPORT="${PGPORT:-55432}"
DB="${MMO_DB:-mmo}"
RUN=()
if [ "$(id -u)" = "0" ]; then RUN=(runuser -u postgres --); fi   # postgres refuses to run as root

as_pg() { "${RUN[@]}" "$@"; }

init() {
  mkdir -p "$DEV"
  if [ ! -f "$DEV/env" ]; then
    umask 077
    cat > "$DEV/env" <<ENV
# generated by tools/db/dev_db.sh - development only, never commit
export PGPORT=$PGPORT
export MMO_DB_PASSWORD=$(head -c 24 /dev/urandom | base64 | tr -d '/+=')
export KEEPER_SECRET=$(head -c 32 /dev/urandom | base64 | tr -d '/+=')
export KEEPER_DSN="host=127.0.0.1 port=$PGPORT dbname=$DB user=mmo_keeper password=\$MMO_DB_PASSWORD"
export KEEPER_ITEMS="$ROOT/game/data/items.json"
export KEEPER_ENV=development
ENV
  fi
  # shellcheck disable=SC1091
  source "$DEV/env"
  if [ ! -d "$PGDATA" ]; then
    mkdir -p "$PGDATA"; [ ${#RUN[@]} -gt 0 ] && chown -R postgres "$DEV" && chmod 755 "$DEV"
    PWF="$(mktemp)"; head -c 24 /dev/urandom | base64 > "$PWF"; [ ${#RUN[@]} -gt 0 ] && chown postgres "$PWF"
    as_pg "$PGBIN/initdb" -D "$PGDATA" -U postgres -E UTF8 --locale=C.UTF-8 --auth=scram-sha-256 --pwfile="$PWF" >/dev/null
    cp "$PWF" "$DEV/.superuser_pw"; rm -f "$PWF"; chmod 600 "$DEV/.superuser_pw"
    echo "listen_addresses = '127.0.0.1'" >> "$PGDATA/postgresql.conf"
    echo "port = $PGPORT" >> "$PGDATA/postgresql.conf"
    echo "unix_socket_directories = '$DEV'" >> "$PGDATA/postgresql.conf"
  fi
  start
  PGPASSWORD="$(cat "$DEV/.superuser_pw")" psql -h 127.0.0.1 -p "$PGPORT" -U postgres -v ON_ERROR_STOP=1 -q <<SQL
DO \$\$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'mmo_keeper') THEN
    CREATE ROLE mmo_keeper LOGIN PASSWORD '$MMO_DB_PASSWORD';
  END IF;
END \$\$;
SQL
  if ! PGPASSWORD="$(cat "$DEV/.superuser_pw")" psql -h 127.0.0.1 -p "$PGPORT" -U postgres -Atc "SELECT 1 FROM pg_database WHERE datname='$DB'" | grep -q 1; then
    PGPASSWORD="$(cat "$DEV/.superuser_pw")" psql -h 127.0.0.1 -p "$PGPORT" -U postgres -qc "CREATE DATABASE $DB OWNER mmo_keeper ENCODING 'UTF8' TEMPLATE template0"
  fi
  python3 "$ROOT/tools/keeper/keeper.py" migrate
}

start() {
  if as_pg "$PGBIN/pg_ctl" -D "$PGDATA" status >/dev/null 2>&1; then return; fi
  as_pg "$PGBIN/pg_ctl" -D "$PGDATA" -l "$PGDATA/server.log" -w start >/dev/null
  echo "postgres running on 127.0.0.1:$PGPORT"
}

stop() { as_pg "$PGBIN/pg_ctl" -D "$PGDATA" -m fast -w stop >/dev/null && echo "postgres stopped" || true; }

case "${1:-}" in
  init) init ;;
  start) start ;;
  stop) stop ;;
  status) as_pg "$PGBIN/pg_ctl" -D "$PGDATA" status ;;
  psql) source "$DEV/env"; shift; PGPASSWORD="$MMO_DB_PASSWORD" exec psql -h 127.0.0.1 -p "$PGPORT" -U mmo_keeper "$DB" "$@" ;;
  reset) source "$DEV/env"
         PGPASSWORD="$(cat "$DEV/.superuser_pw")" psql -h 127.0.0.1 -p "$PGPORT" -U postgres -qc "DROP DATABASE IF EXISTS $DB WITH (FORCE)"
         init ;;
  *) echo "usage: $0 init|start|stop|status|psql|reset"; exit 2 ;;
esac
